export type SourceCheck = 'fulltext' | 'abstract'
export const SOURCE_CHECK_LABEL: Record<SourceCheck, string> = { fulltext: '全文を確認', abstract: '抄録を確認' }

export interface ProgramSource {
  /** 著者（年）雑誌 */
  label: string
  pmid?: string
  doi: string
  checked: SourceCheck
  /** その文献に書いてあったこと（確かめた範囲だけ） */
  found: string
}

export interface ProgramStage {
  /** 保存値。変えない */
  id: string
  /** 短い名前（「、」「。」を入れない＝SOAP に入れる文に使う） */
  title: string
  /** やること（目安） */
  doing: string[]
  /** 次へ進む目安（無ければ、プログラムの「進め方の決まり」で進める） */
  advance?: string[]
}

export interface ReturnProgram {
  /** 保存値。変えない */
  id: string
  title: string
  /** 短い名前（SOAP に入れる文・一覧） */
  short: string
  regions: BodyRegion[]
  /** だれのためのプログラムか・使わない方 */
  forWhom: string
  /** 始める前に確かめること */
  before: string[]
  /** 進め方の決まり */
  rules: string[]
  stages: ProgramStage[]
  /** 中止して院長が判断し、必要なら医師へ */
  stop: string[]
  /** 文献で分かっていること・分かっていないこと */
  evidence: string
  /** 文献で確かめられなかったこと（院長が確かめて決める） */
  unverified?: string[]
  sources: ProgramSource[]
}

