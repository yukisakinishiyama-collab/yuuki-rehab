// ──────────────────────────────────────────────
// ストア共通：保存後のクラウド同期通知
//
// 本番アプリは起動時に pullFromCloud() が localStorage をクラウドの内容で
// まるごと上書きする。そのため「保存してもクラウドへ push しないストア」の
// データは、次にアプリを開いた瞬間に古い内容へ巻き戻る（実際に、がんばり
// レポートのAI文章が印刷前に消える不具合として発生した）。
//
// localStorage に書き込むストアは、保存のたびに必ずこれを呼ぶこと。
// 同期が無効な環境（ローカル開発・シークレット未設定）では何もしない。
// ──────────────────────────────────────────────
export function notifyCloudSync(): void {
  if (typeof window === 'undefined') return
  import('./sync-service')
    .then(({ scheduleSync }) => scheduleSync())
    .catch(() => { /* 同期は付加機能。失敗しても保存自体は成立している */ })
}
